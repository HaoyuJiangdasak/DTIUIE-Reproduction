"""Generate an operational copy of the author's trainer; never edit its source."""

import ast
import hashlib
from pathlib import Path


DIRECTORY = Path(__file__).resolve().parent
PROJECT_ROOT = DIRECTORY.parent


def replace_once(source, old, new, label):
    count = source.count(old)
    if count != 1:
        raise ValueError("{}: expected one exact source anchor, found {}".format(label, count))
    return source.replace(old, new, 1)


def build():
    original = PROJECT_ROOT / "underwater_train.py"
    original_bytes = original.read_bytes()
    original_hash = hashlib.sha256(original_bytes).hexdigest()
    source = original_bytes.decode("utf-8-sig").replace("\r\n", "\n")
    prefix = (
        "# Generated by build_monitored_train.py; original training mathematics retained.\n"
        "import sys\n"
        "from pathlib import Path\n"
        "sys.path.insert(0, str(Path(__file__).resolve().parent.parent))\n"
        "from training_observer import TrainingObserver\n"
        "DTIUIE_ORIGINAL_SOURCE_SHA256 = {!r}\n"
        "dtiuie_observer = None\n\n"
    ).format(original_hash)
    source = prefix + source
    source = replace_once(source, "    return parser.parse_args()\n", (
        "    parser.add_argument('--run_dir', default=None, type=str, help='Operational records and rolling full checkpoint directory')\n"
        "    parser.add_argument('--resume_full', default=None, type=str, help='Explicit trusted full checkpoint from this monitored trainer')\n"
        "    parser.add_argument('--cudnn_benchmark', action='store_true', default=False, help='Enable cuDNN kernel autotuning; does not enable AMP')\n"
        "    return parser.parse_args()\n"
    ), "operational CLI")
    source = replace_once(source, "def train_model(args):\n", (
        "def train_model(args):\n"
        "    global current_time, dtiuie_observer\n"
        "    dtiuie_observer = TrainingObserver(args, current_time, __file__, DTIUIE_ORIGINAL_SOURCE_SHA256)\n"
        "    args, current_time = dtiuie_observer.prepare()\n"
        "    if args.cudnn_benchmark:\n"
        "        torch.backends.cudnn.benchmark = True\n"
    ), "observer initialization")
    source = replace_once(source, "    for epoch in range(1, args.epochs + 1):\n", (
        "    dtiuie_start_epoch, global_step, best_criterions = dtiuie_observer.bind(\n"
        "        args=args, current_time=current_time, device=device,\n"
        "        models={'model_E': model_E, 'model_S': model_S, 'model_SA': model_SA},\n"
        "        optimizers={'optimizer_E': optimizer, 'optimizer_S': optimizer_seg, 'optimizer_SA': optimizer_sa},\n"
        "        schedulers={'scheduler_E': scheduler, 'scheduler_S': scheduler_seg, 'scheduler_SA': scheduler_sa},\n"
        "        scalers={'scaler_E': scaler, 'scaler_S': scaler_seg, 'scaler_SA': scaler_sa},\n"
        "        best_criterions=best_criterions, global_step=global_step, total_batches=len(train_loader))\n"
        "    epoch = dtiuie_start_epoch - 1\n"
        "    for epoch in range(dtiuie_start_epoch, args.epochs + 1):\n"
    ), "full-state restoration before next epoch")
    for loss, scaler, label in (
        ("loss_sa_total", "scaler_sa", "SA"),
        ("loss_enc_total", "scaler", "E"),
        ("loss_seg_total", "scaler_seg", "S"),
    ):
        anchor = "                {}.scale({}).backward()\n".format(scaler, loss)
        source = replace_once(source, anchor, (
            "                dtiuie_observer.check_loss({}, {!r}, epoch, i + 1, global_step)\n".format(loss, label)
            + anchor
        ), "finite loss guard " + label)
    source = replace_once(source, "                global_step = global_step + 1\n", (
        "                global_step = global_step + 1\n"
        "                dtiuie_observer.iteration(epoch, i + 1, len(train_loader), global_step, loss_enc_total, loss_seg_total, loss_sa_total)\n"
    ), "heartbeat after completed iteration")
    source = replace_once(source, "    # TRAINING_COMPLETED.\n", (
        "        dtiuie_observer.epoch_complete(epoch, global_step, best_criterions, args, current_time)\n\n"
        "    # TRAINING_COMPLETED.\n"
    ), "rolling full checkpoint after original best saves")
    source = replace_once(source, "    writer.close()\n", (
        "    writer.close()\n"
        "    dtiuie_observer.complete(epoch, global_step)\n"
    ), "completion marker after original final save and writer close")
    source = replace_once(source, "    train_model(args=args)\n", (
        "    try:\n"
        "        train_model(args=args)\n"
        "    except BaseException as error:\n"
        "        if dtiuie_observer is not None:\n"
        "            dtiuie_observer.fail(error)\n"
        "        raise\n"
    ), "exception status")
    ast.parse(source, filename="underwater_train_monitored.py")
    target = DIRECTORY / "underwater_train_monitored.py"
    target.write_bytes(source.encode("utf-8"))
    generated_hash = hashlib.sha256(target.read_bytes()).hexdigest()
    notes = """# Monitored training patch notes

Original: `../underwater_train.py`
Original SHA256: `{original_hash}`
Generated copy SHA256: `{generated_hash}`

Regenerate with `python cloud_reproduction/build_monitored_train.py` from the project root.
The builder requires each exact anchor to occur once and checks the generated AST.
Original files are never edited. Only `underwater_train_monitored.py` and these notes are generated.

Operational additions:
- `--run_dir`: an empty new directory for `run_metadata.json`, atomic `heartbeat.json`,
  rolling `latest_full.pth`, and a `completed.json` or `failed.json` marker.
- Heartbeat every 10 completed global iterations, additionally the first/last batch of each epoch.
  Reports the three losses, epoch/batch/global step, PID, elapsed time, GPU peak memory,
  actual optimizer learning rates/weight decay, and all three GradScaler scales.
- Fail on non-finite phase loss before backward. No gradient clipping or loss modification.
- After validation and the author's best saves each epoch, atomically replace this run's
  rolling full checkpoint. It contains three models/optimizers/schedulers/scalers,
  Python/NumPy/Torch/CUDA RNG, best criteria, global step, completed epoch, args, and timestamp.
- `--resume_full`: restore this monitored format and start at the next epoch. A checkpoint
  after epoch 100 can finish the original final evaluation/save without another training epoch.
  Restore RNG only after constructor initialization. Keep the saved training configuration
  and timestamp; `--run_dir` can select a new recovery directory. An explicitly supplied
  `--cudnn_benchmark` can enable autotuning on recovery.
- `--cudnn_benchmark`: enable cuDNN kernel autotuning only. AMP is not enabled.
- Finish/error markers are operational status, not new evaluation metrics.

Author behavior intentionally retained: L1/nearest; default batch 4, 100 epochs, warmup 10;
inactive seed CLI; actual AdamW default weight decay 0.01; unweighted three CE losses;
SA scheduler's original binding and absence of stepping; original mode/gradient behavior;
original best/final evaluation network choice and metric code; original best/final filenames.
The ineffective original `--resume`/`--pretrained` options are not used by the observer.
Do not enable the author's broken `--save_iter_checkpoint` branch.

Launch from the project root. Resume only full checkpoints produced by this observer.
Ordinary author checkpoints and the released inference checkpoint are not resumable here.
""".format(original_hash=original_hash, generated_hash=generated_hash)
    (DIRECTORY / "PATCH_NOTES.md").write_bytes(notes.encode("utf-8"))
    print("Generated: {}\nOriginal SHA256: {}\nCopy SHA256: {}".format(target, original_hash, generated_hash))


if __name__ == "__main__":
    build()
